#:property PublishAot=false
#:property RestorePackagesWithLockFile=false
// Local development secrets (plan P12, D-08). Usage, from the repository root:
//
//   dotnet run scripts/dev-env.cs [-- --force] [-- --output <path>]
//
// Generates an RSA-3072 JWT signing key and random Postgres, Redis and S3 (RustFS) credentials, fills every CHANGE_ME of
// deploy/compose/.env.example with them and writes the result to deploy/compose/.env (gitignored; never commit it, INV-11).
// It also prints the 'dotnet user-secrets' commands that give a local 'dotnet run' of the Host the same signing key.
// Refuses to overwrite an existing file unless --force is given.
// No packages are used; the directives above stop the file-based app from writing a platform-specific lock file.

using System.Globalization;
using System.Security.Cryptography;
using System.Text;

const string HostProject = "src/Host/Acme.Service.Host";
const string DefaultOutput = "deploy/compose/.env";
const string TemplateFile = "deploy/compose/.env.example";
const string Placeholder = "CHANGE_ME";
const string PasswordAlphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";

var force = false;
string? output = null;
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--force":
            force = true;
            break;
        case "--output" when i + 1 < args.Length:
            output = args[++i];
            break;
        case "-h" or "--help":
            Console.WriteLine("Usage: dotnet run scripts/dev-env.cs [-- --force] [-- --output <path>]");
            return 0;
        default:
            Console.Error.WriteLine($"Unknown argument '{args[i]}'. Use --force and/or --output <path>.");
            return 2;
    }
}

var root = FindRepositoryRoot(Directory.GetCurrentDirectory());
if (root is null)
{
    Console.Error.WriteLine("Run this script from inside the repository (Acme.Service.slnx was not found).");
    return 2;
}

var envPath = Path.GetFullPath(output ?? Path.Combine(root, DefaultOutput));
if (File.Exists(envPath) && !force)
{
    Console.Error.WriteLine($"{envPath} already exists; nothing was changed. Re-run with --force to replace it (the old key and passwords are lost).");
    return 1;
}

using var rsa = RSA.Create(3072);
var privateKeyBase64 = Convert.ToBase64String(Encoding.UTF8.GetBytes(rsa.ExportPkcs8PrivateKeyPem()));
var now = DateTimeOffset.UtcNow;
var kid = string.Create(CultureInfo.InvariantCulture, $"dev-{now:yyyyMMdd}-{Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(4))}");
var postgresPassword = RandomNumberGenerator.GetString(PasswordAlphabet, 32);
var redisPassword = RandomNumberGenerator.GetString(PasswordAlphabet, 32);
var s3User = "dev-" + RandomNumberGenerator.GetString(PasswordAlphabet, 8).ToLowerInvariant();
var s3Password = RandomNumberGenerator.GetString(PasswordAlphabet, 40);

// Every key of deploy/compose/.env.example whose value is CHANGE_ME must have a generator here, so the generated .env
// is always complete; all other keys (ports, switches, fixed settings) are copied from the template unchanged.
var generated = new Dictionary<string, string>(StringComparer.Ordinal)
{
    ["POSTGRES_PASSWORD"] = postgresPassword,
    ["REDIS_PASSWORD"] = redisPassword,
    ["S3_ROOT_USER"] = s3User,
    ["S3_ROOT_PASSWORD"] = s3Password,
    ["Auth__Jwt__SigningKeys__0__Kid"] = kid,
    ["Auth__Jwt__SigningKeys__0__PrivateKeyBase64"] = privateKeyBase64,
};

var templatePath = Path.Combine(root, TemplateFile);
if (!File.Exists(templatePath))
{
    Console.Error.WriteLine($"Template {templatePath} was not found.");
    return 2;
}

var content = new StringBuilder()
    .AppendLine(CultureInfo.InvariantCulture, $"# Generated by scripts/dev-env.cs at {now:u} from .env.example. Local development only; never commit this file.");
var unfilled = new List<string>();
foreach (var line in File.ReadAllLines(templatePath))
{
    var separator = line.IndexOf('=', StringComparison.Ordinal);
    if (line.StartsWith('#') || separator <= 0 || line[(separator + 1)..] != Placeholder)
    {
        content.AppendLine(line);
        continue;
    }

    var key = line[..separator];
    if (generated.TryGetValue(key, out var value))
    {
        content.AppendLine(key + "=" + value);
    }
    else
    {
        unfilled.Add(key);
    }
}

if (unfilled.Count > 0)
{
    Console.Error.WriteLine($"No generator for: {string.Join(", ", unfilled)}. Add one to scripts/dev-env.cs; nothing was written.");
    return 2;
}

Directory.CreateDirectory(Path.GetDirectoryName(envPath)!);
File.WriteAllText(envPath, content.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
if (!OperatingSystem.IsWindows())
{
    File.SetUnixFileMode(envPath, UnixFileMode.UserRead | UnixFileMode.UserWrite);
}

Console.WriteLine($"Wrote {envPath} (signing key '{kid}', RSA-3072).");
Console.WriteLine();
Console.WriteLine("For a local 'dotnet run' of the Host, store the same values in user-secrets (they stay outside the repository):");
Console.WriteLine();
Console.WriteLine($"  dotnet user-secrets set \"Auth:Jwt:SigningKeys:0:Kid\" \"{kid}\" --project {HostProject}");
Console.WriteLine($"  dotnet user-secrets set \"Auth:Jwt:SigningKeys:0:Status\" \"Active\" --project {HostProject}");
Console.WriteLine($"  dotnet user-secrets set \"Auth:Jwt:SigningKeys:0:PrivateKeyBase64\" \"{privateKeyBase64}\" --project {HostProject}");
Console.WriteLine($"  dotnet user-secrets set \"ConnectionStrings:Postgres\" \"Host=localhost;Port=5432;Database=acme_service;Username=postgres;Password={postgresPassword}\" --project {HostProject}");
Console.WriteLine($"  dotnet user-secrets set \"ConnectionStrings:PostgresMigrations\" \"Host=localhost;Port=5432;Database=acme_service;Username=postgres;Password={postgresPassword}\" --project {HostProject}");
Console.WriteLine();
Console.WriteLine("These commands contain secrets: run them in a private terminal and do not paste them into tickets or chat.");
return 0;

static string? FindRepositoryRoot(string start)
{
    for (var directory = new DirectoryInfo(start); directory is not null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "Acme.Service.slnx")))
        {
            return directory.FullName;
        }
    }

    return null;
}
